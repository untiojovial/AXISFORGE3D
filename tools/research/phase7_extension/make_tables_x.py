"""Write the manuscript macros and tables for the Phase VII extension from the stored results (nothing typed by hand).

    python tools/research/phase7_extension/make_tables_x.py --out publication/intelligent_service_robotics/tables

Inputs: research/phase7_extension/results/*.json (P2 audit, corrections addendum, integrated benchmark, memory,
ordering ceiling, v3 models, external baselines v2, GPD variability, fallback audit, native validation,
confirmation_x.json if present). Outputs: numbers_x.tex (one \\newcommand per number) and tab_x_confirmation.tex.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
R = ROOT/'research/phase7_extension/results'


class Macros:
    def __init__(self):
        self.lines = ['% Generated by tools/research/phase7_extension/make_tables_x.py from research/phase7_extension/results. Do not edit.']

    placeholder = False

    def add(self, name, value):
        if self.placeholder and name.startswith('nx'):
            value = '\\textbf{??}'
        self.lines.append(f'\\newcommand{{\\{name}}}{{{value}}}')


def f(x, d=2):
    return f'{x:.{d}f}'


def pp(x, d=1):
    return f'{100*x:.{d}f}'


def ci(a, d=2, scale=1.):
    return f'[{a[0]*scale:.{d}f}, {a[1]*scale:.{d}f}]'


def load(name):
    p = R/name
    return json.loads(p.read_text()) if p.exists() else None


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--out', required=True)
    p.add_argument('--confirmation', default=str(R/'confirmation_x.json'), help='confirmation_x.json (default: the committed result)')
    p.add_argument('--placeholder', action='store_true',
                   help='layout only: write every new-confirmation macro as ?? (used to size the manuscript before the result exists)')
    a = p.parse_args()
    M = Macros()
    # P2 audit (historical)
    p2 = load('p2_statistical_audit.json')
    M.add('auditTangoP', f(p2['tango']['p_one_sided'], 3)); M.add('auditTangoCI', ci(p2['tango']['ci95'], 1, 100))
    M.add('auditNewcombeCI', ci(p2['newcombe_method10']['ci95'], 1, 100))
    M.add('auditFragP', f(p2['fragility_pre_specified']['one Joint-only object becomes neither']['p_one_sided'], 3))
    M.add('auditDiscFav', p2['paired_table']['joint_only']); M.add('auditDiscUnfav', p2['paired_table']['m0_only'])
    ad = load('corrections_addendum.json')['F_full_precision_holm_primary']
    M.add('auditPoneHolm', '{:.1e}'.format(next(v['holm_p_full_precision'] for k, v in ad.items() if k.startswith('P1'))).replace('e-0', 'e-'))
    # native implementation
    nv = load('native_inference_validation.json')['summary']; nx = load('native_inference_validation_x.json')['summary']
    M.add('natCandidates', f"{nv['development']['candidates'] + nv['egad']['candidates']:,}".replace(',', '\\,'))
    M.add('natObjects', nv['development']['objects'] + nv['egad']['objects'])
    M.add('natDecisionObjects', nv['development']['decisions']['joint']['objects'] + nv['egad']['decisions']['joint']['objects'])
    M.add('natXDecisionObjects', nx['development']['decisions']['joint']['objects'] + nx['egad']['decisions']['joint']['objects'])
    bm = load('integrated_runtime_benchmark.json')
    for kind, tag in (('development', 'Dev'), ('egad', 'Egad'), ('all', 'All')):
        r = bm['results'][kind]
        M.add(f'bench{tag}Objects', r['objects'])
        M.add(f'bench{tag}Cold', f(r['cold_wall']['joint']['ratio_gmean'], 3)); M.add(f'bench{tag}ColdCI', ci(r['cold_wall']['joint']['ci95'], 3))
        M.add(f'bench{tag}Warm', f(r['warm_steady']['joint']['ratio_gmean'], 3)); M.add(f'bench{tag}WarmCI', ci(r['warm_steady']['joint']['ci95'], 3))
        M.add(f'bench{tag}Faster', r['cold_wall']['joint']['faster']); M.add(f'bench{tag}Slower', r['cold_wall']['joint']['slower'])
        M.add(f'bench{tag}MzeroMedian', f(r['cold_wall']['M0']['absolute']['median'], 3))
        M.add(f'bench{tag}JointMedian', f(r['cold_wall']['joint']['absolute']['median'], 3))
    st = bm['results']['all']['stages']['joint']
    M.add('benchInferenceMs', f(1e3*st['learned_stages']['inference']['median'], 1))
    M.add('benchLearnedMs', f(1e3*st['learned_total']['median'], 1)); M.add('benchGenerationMs', f(1e3*st['generation']['median'], 0))
    M.add('benchModelLoadMs', f(1e3*st['model_load']['median'], 1))
    mem = load('memory_benchmark.json')
    M.add('memMzeroMiB', f(mem['summary']['M0']['median_mib'], 1)); M.add('memExtraMiB', f(mem['summary']['joint']['median_minus_M0_mib'], 1))
    M.add('modelMB', f(mem['model_file_bytes']/1e6, 2))
    ce = load('ordering_ceiling.json')['results']
    M.add('ceilDevMs', f(ce['development']['oracle_saving_ms_mean'], 1)); M.add('ceilEgadMs', f(ce['egad']['oracle_saving_ms_mean'], 1))
    M.add('ceilDevShare', pp(ce['development']['oracle_saving_share_mean'], 2)); M.add('ceilEgadShare', pp(ce['egad']['oracle_saving_share_mean'], 2))
    fb = load('fallback_audit.json')['summary']
    M.add('fbObjects', fb['development']['objects'] + fb['egad']['objects'])
    M.add('fbViolations', fb['development']['violations'] + fb['egad']['violations'])
    # v3 models and selection (development)
    v3 = load('v3_models.json')
    o = v3['ordering']
    for m, tag in (('M0', 'Mzero'), ('M1', 'Mone'), ('Joint', 'Joint'), ('Joint-v3', 'JointVthree'), ('Joint-multi', 'Multi'), ('Joint-load', 'Load')):
        M.add(f'vNF{tag}', f(o[m]['N_F_gmean'])); M.add(f'vAll{tag}', pp(o[m]['robust_y_all3'])); M.add(f'vStd{tag}', pp(o[m]['robust_y_std']))
        M.add(f'vLoad{tag}', pp(o[m]['load']))
    M.add('vGuard', f(v3['selection']['efficiency_guard_N_F'], 3)); M.add('vAdv', f(v3['selection']['advantage_over_M1_pp'], 1))
    M.add('vSimulated', v3['coverage']['simulated_total']); M.add('vViable', v3['coverage']['viable_total'])
    M.add('vAUCall', f(v3['probability_metrics']['GB-all3']['y_all3']['auc'], 3))
    M.add('vECEall', f(v3['probability_metrics']['GB-all3']['y_all3']['ece'], 3))
    # GPD (development, ranking-controlled)
    eb = load('external_baselines_v2.json')['development']; gp = eb['methods']
    for m, tag in (('M0', 'Mzero'), ('M1', 'Mone'), ('Joint', 'Joint')):
        M.add(f'gpdDevNF{tag}', f(gp[m]['N_F_gmean'])); M.add(f'gpdDevRob{tag}', pp(gp[m]['robust_v3'])); M.add(f'gpdDevLoad{tag}', pp(gp[m]['load_tolerant_v3']))
    M.add('gpdDevObjects', gp['GPD+gate']['objects'])
    cgm = eb['contrasts']['GPD+gate vs M0']
    M.add('gpdVsMzeroNF', f(cgm['N_F_ratio']['ratio'])); M.add('gpdVsMzeroNFCI', ci(cgm['N_F_ratio']['ci95']))
    M.add('gpdVsMzeroLoad', pp(cgm['load_difference']['difference'])); M.add('gpdVsMzeroLoadCI', ci(cgm['load_difference']['ci95'], 1, 100))
    cgj = eb['contrasts']['GPD+gate vs Joint']
    M.add('gpdVsJointLoad', pp(cgj['load_difference']['difference'])); M.add('gpdVsJointLoadCI', ci(cgj['load_difference']['ci95'], 1, 100))
    M.add('gpdNF', f(gp['GPD+gate']['N_F_gmean'])); M.add('gpdRobust', pp(gp['GPD+gate']['robust_v3'])); M.add('gpdLoad', pp(gp['GPD+gate']['load_tolerant_v3']))
    M.add('gpdSone', pp(gp['GPD+gate']['success_at'][1] if 1 in gp['GPD+gate']['success_at'] else gp['GPD+gate']['success_at']['1']))
    gv = load('gpd_variability.json')
    M.add('gpdVarObjects', gv['objects']); M.add('gpdVarCorr', f(gv['score_correlation']['median'], 2)); M.add('gpdVarSame', gv['same_first_grasp'])
    M.add('gpdSeconds', f(gv['stage_seconds_median']['images'] + gv['stage_seconds_median']['classify'] + gv['stage_seconds_median']['cloud_preprocess'], 1))
    M.add('gpdRenderSeconds', f(gv['render_seconds_median'], 2))
    # new confirmation
    cx = json.loads(Path(a.confirmation).read_text()) if Path(a.confirmation).exists() else None
    M.placeholder = a.placeholder
    if cx:
        c = cx['counts']; M.add('nxObjects', c['objects']); M.add('nxCatalogued', c['catalogued']); M.add('nxViable', c['viable'])
        M.add('nxNoViable', c['no_viable_candidate']); M.add('nxPrepFail', c['preparation_failures'])
        word = dict(C1='Cone', C2='Ctwo', C3='Cthree', C4='Cfour', S1='Sone', S2='Stwo', S3='Sthree')  # no digits in TeX names
        for k in ('C1', 'C2', 'C3', 'C4'):
            v = cx['primary'][k]; k = word[k]
            M.add(f'nx{k}Verdict', 'supported' if v['supported'] else 'not supported'); M.add(f'nx{k}Holm', '{:.2g}'.format(v['holm_p']))
            if 'gmean_ratio' in v:
                M.add(f'nx{k}Eff', f(v['gmean_ratio'], 3)); M.add(f'nx{k}CI', ci(v['ci95'], 3))
            else:
                M.add(f'nx{k}Eff', pp(v['difference'])); M.add(f'nx{k}CI', ci(v['tango_ci95'], 1, 100))
                M.add(f'nx{k}Newcombe', ci(v['newcombe_ci95'], 1, 100)); M.add(f'nx{k}Fav', v['x_only']); M.add(f'nx{k}Unfav', v['y_only'])
        for k, v in cx['secondary'].items():
            tag = word[k.split()[0]]
            M.add(f'nx{tag}Verdict', 'supported' if v['supported'] else 'not supported'); M.add(f'nx{tag}Eff', pp(v['difference']))
            M.add(f'nx{tag}CI', ci(v['tango_ci95'], 1, 100)); M.add(f'nx{tag}Holm', '{:.2g}'.format(v['holm_p']))
        rt = cx['rates']
        for m, tag in (('M0', 'Mzero'), ('M1', 'Mone'), ('Joint-hist', 'Jhist'), ('Joint-multi', 'X')):
            M.add(f'nxNF{tag}', f(rt[m]['N_F_gmean'])); M.add(f'nxRob{tag}', pp(rt[m]['robust_v3'])); M.add(f'nxAll{tag}', pp(rt[m]['robust_all3']))
            M.add(f'nxLoad{tag}', pp(rt[m]['load']))
        if 'GPD+gate' in rt:
            M.add('nxNFGPD', f(rt['GPD+gate']['N_F_gmean'])); M.add('nxRobGPD', pp(rt['GPD+gate']['robust_v3'])); M.add('nxLoadGPD', pp(rt['GPD+gate']['load']))
        M.add('nxFbViol', cx['descriptive']['fallback']['violations']); M.add('nxHybridNF', f(cx['descriptive']['fallback']['hybrid_nf_gmean']))
        for k in ('C1', 'C3', 'C4'):
            v = cx['primary'][k]; t = word[k]
            M.add(f'nx{t}Fewer', v['fewer']); M.add(f'nx{t}More', v['more']); M.add(f'nx{t}Ties', v['ties']); M.add(f'nx{t}N', v['n'])
        M.add('nxCthreeUpper', f(cx['primary']['C3']['upper_97_5'], 3))
        M.add('nxConeWilcoxonP', '{:.2g}'.format(cx['primary']['C1']['wilcoxon']['p_one_sided']))
        M.add('nxCfourWilcoxonP', '{:.2g}'.format(cx['primary']['C4']['wilcoxon']['p_one_sided']))
        v = cx['primary']['C2']; M.add('nxCtwoBoth', v['both']); M.add('nxCtwoNeither', v['neither']); M.add('nxCtwoN', v['n'])
        M.add('nxCtwoP', '{:.2g}'.format(v['p_one_sided'])); M.add('nxCtwoMcnemar', '{:.2g}'.format(v['mcnemar_superiority_p_one_sided']))
        c = cx['counts']
        M.add('nxPlanErrors', c['planning_errors']); M.add('nxReplayMzero', len(c['replay_mismatches_M0'])); M.add('nxReplayLearned', len(c['replay_mismatches_learned']))
        M.add('nxUnstable', c['simulation_unstable_trials']); M.add('nxTrials', f"{c['simulation_trials']:,}".replace(',', '\\,'))
        M.add('nxCatFail', sum(c['catalogue_failures'].values()))
        for m, tag in (('M0', 'Mzero'), ('Joint-multi', 'X'), ('GPD+gate', 'GPD')):
            if m in rt:
                M.add(f'nxSone{tag}', pp(rt[m]['success_at']['1'] if '1' in rt[m]['success_at'] else rt[m]['success_at'][1]))
        d = cx['descriptive']
        for key, tag in (('X vs Joint-hist robust v3 (two-sided)', 'XJhRob'), ('X vs Joint-hist load (two-sided)', 'XJhLoad'),
                         ('X vs M0 robust at torsion 0.001', 'TorLow'), ('X vs M0 robust at torsion 0.02', 'TorHigh'),
                         ('GPD+gate vs M0 robust v3', 'GPDRob'), ('GPD+gate vs M0 load', 'GPDLoad')):
            if key in d:
                M.add(f'nx{tag}', pp(d[key]['difference'])); M.add(f'nx{tag}CI', ci(d[key]['tango_ci95'], 1, 100))
        for key, tag in (('X/Joint-hist N_F', 'XJhNF'), ('GPD+gate/M0 N_F (two-sided reading)', 'GPDNF')):
            if key in d:
                M.add(f'nx{tag}', f(d[key]['gmean_ratio'], 3)); M.add(f'nx{tag}CI', ci(d[key]['ci95'], 3))
        M.add('nxTimed', cx['timed_objects']); M.add('nxTimeMzeroPninetyfive', f(cx['timing']['M0']['p95_s'], 3))
        M.add('nxTimeXPninetyfive', f(cx['timing']['Joint-multi']['p95_s'], 3))
        M.add('nxLoadBefore', f(cx['load_during_timing']['median_before'], 2)); M.add('nxClusters', cx['cluster_sensitivity']['clusters'])
        M.add('nxClusterCthree', ci(cx['cluster_sensitivity']['C3_gmean_ratio'], 3))
        M.add('nxTimeMzero', f(cx['timing']['M0']['median_s'], 3)); M.add('nxTimeX', f(cx['timing']['Joint-multi']['median_s'], 3))
        cl = cx['cluster_sensitivity']
        M.add('nxClusterCone', ci(cl['C1_gmean_ratio'], 3)); M.add('nxClusterCtwo', ci(cl['C2_difference'], 1, 100))
        M.add('nxClusterCfour', ci(cl['C4_gmean_ratio'], 3))
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    # development table on the 151 dynamic parts: v3 labels, identical population for every row
    rows = [('M0 (original planner)', o['M0']), ('M1 (learned feasibility)', o['M1']), ('Joint (Phase VII)', o['Joint']),
            ('Joint-multi (X)', o['Joint-multi'])]
    tab = ['\\begin{tabular}{lrrrr}', '\\toprule', 'Order & $N_F$ & Robust & All 3 torsions & Load \\\\', '\\midrule']
    for name, r in rows:
        tab.append(f"{name} & {f(r['N_F_gmean'])} & {pp(r['robust_y_std'])} & {pp(r['robust_y_all3'])} & {pp(r['load'])} \\\\")
    g = gp['GPD+gate']
    tab.append(f"GPD+gate & {f(g['N_F_gmean'])} & {pp(g['robust_v3'])} & -- & {pp(g['load_tolerant_v3'])} \\\\")
    tab += ['\\bottomrule', '\\end{tabular}']
    (out/'tab_x_dev.tex').write_text('\n'.join(tab) + '\n')
    # supplementary benchmark table (integrated implementation, not confirmatory)
    tab = ['\\begin{tabular}{lrlrrr}', '\\toprule',
           'Order & Cold & 95\\% CI & $+$/$-$ & Warm & Median (ms) \\\\', '\\midrule']
    for kind, kname in (('development', 'Development parts'), ('egad', 'EGAD objects of the first confirmation')):
        r = bm['results'][kind]
        tab.append(f"\\multicolumn{{6}}{{l}}{{\\emph{{{kname} ({r['objects']})}}}} \\\\")
        tab.append(f"M0 & 1 & -- & -- & 1 & {1e3*r['cold_wall']['M0']['absolute']['median']:.0f} \\\\")
        for m, mn in (('m1', 'M1'), ('m4', 'M4'), ('m9', 'M9'), ('joint', 'Joint'), ('hybrid', 'Hybrid')):
            c, w = r['cold_wall'][m], r['warm_steady'][m]
            tab.append(f"{mn} & {f(c['ratio_gmean'], 3)} & {ci(c['ci95'], 3)} & {c['faster']}/{c['slower']} & {f(w['ratio_gmean'], 3)} & {1e3*c['absolute']['median']:.0f} \\\\")
    tab += ['\\bottomrule', '\\end{tabular}']
    (out/'tab_x_bench.tex').write_text('\n'.join(tab) + '\n')
    env = bm['environment']
    M.add('benchCPU', env['cpu_model'].replace('(R)', '')); M.add('benchOtherLoad', f"{sum(float(x.split()[0]) for x in env['other_processes_at_start']):.0f}")
    if cx:
        q = (lambda v: '??') if a.placeholder else (lambda v: v)
        tab = ['\\begin{tabular}{llllll}', '\\toprule', ' & Effect & 95\\% CI & $+$/$-$/$=$ & Holm $p$ & Verdict \\\\', '\\midrule']
        lab = dict(C1='C1 $N_F$ ratio X/M0', C2='C2 robust X$-$M0 (pp)', C3='C3 $N_F$ ratio X/M1', C4='C4 time ratio X/M0')
        for k in ('C1', 'C2', 'C3', 'C4'):
            v = cx['primary'][k]
            if 'gmean_ratio' in v:
                eff, c95, cnt = f(v['gmean_ratio'], 3), ci(v['ci95'], 3), f"{v['fewer']}/{v['more']}/{v['ties']}"
            else:
                eff, c95, cnt = pp(v['difference']), ci(v['tango_ci95'], 1, 100), f"{v['x_only']}/{v['y_only']}/{v['both'] + v['neither']}"
            tab.append(f"{lab[k]} & {q(eff)} & {q(c95)} & {q(cnt)} & {q('{:.2g}'.format(v['holm_p']))} & {q('yes' if v['supported'] else 'no')} \\\\")
        tab.append('\\midrule')
        slab = {'S1': 'S1 load X$-$M0 (pp)', 'S2': 'S2 all-3 X$-$M1 (pp)', 'S3': 'S3 all-3 X$-$M0 (pp)'}
        for k, v in cx['secondary'].items():
            t = k.split()[0]
            tab.append(f"{slab[t]} & {q(pp(v['difference']))} & {q(ci(v['tango_ci95'], 1, 100))} & {q(str(v['x_only']) + '/' + str(v['y_only']) + '/' + str(v['both'] + v['neither']))} & "
                       f"{q('{:.2g}'.format(v['holm_p']))} & {q('yes' if v['supported'] else 'no')} \\\\")
        tab += ['\\bottomrule', '\\end{tabular}']
        (out/'tab_x_confirmation.tex').write_text('\n'.join(tab) + '\n')
    (out/'numbers_x.tex').write_text('\n'.join(M.lines) + '\n')
    print(len(M.lines) - 1, 'macros')


if __name__ == '__main__':
    main()
