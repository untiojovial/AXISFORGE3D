"""LaTeX macros and tables for the manuscript, generated only from the stored result files.

    python tools/research/phase7/make_tables.py --results research/phase7/results \
        --out publication/intelligent_service_robotics/tables

Writes numbers.tex (one \\newcommand per number quoted in the text) and one tab_*.tex per table. The
manuscript never types a result by hand: every quoted value is a macro defined here.
"""
import argparse
import json
from pathlib import Path


def tex(text):
    """Escape a plain-text label for LaTeX (N_F becomes math)."""
    out = text.replace('\\', '/').replace('&', '\\&').replace('%', '\\%').replace('#', '\\#')
    out = out.replace('N_F', '@NF@').replace('_', '\\_').replace('@NF@', '$N_F$')
    return out.replace('<', '$<$').replace('>', '$>$').replace('|', '$|$')


def pval(x):
    return '$<10^{-4}$' if x < 1e-4 else f'{x:.2g}'


def pct(x, d=1):
    return f'{100*x:.{d}f}'


def ci(c, scale=1, d=3):
    return f'[{c[0]*scale:.{d}f}, {c[1]*scale:.{d}f}]'


class Macros:
    def __init__(self):
        self.lines = ['% Generated by tools/research/phase7/make_tables.py from research/phase7/results. Do not edit.']

    def __call__(self, name, value):
        assert name.isalpha(), name
        self.lines.append(f'\\newcommand{{\\{name}}}{{{value}}}')


