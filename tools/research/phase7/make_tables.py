    M('repVisibleShare', pct(lf['coverage']['visible_in_at_least_one_view'], 0))
    M('fewFirstShare', pct(few['M1']['N_F']['share_first_candidate'], 0))
    M('fewCeiling', f"{few['M1']['N_F']['mean_extra_candidates']:.2f}")
    M('fewCeilingMs', f"{1e3*few['M1']['N_F']['ceiling_saving_seconds_mean']:.1f}")
    M('fewFixedS', f"{few['fixed_seconds_per_call']:.2f}")
    for g, nm in (('40 mm', 'Forty'), ('120 mm', 'Hundredtwenty')):
        x = cr['grippers'][g]['contrasts']['zero-shot from 80 mm / trained for this gripper']
        M(f'cross{nm}', f"{x['ratio']:.2f}"); M(f'cross{nm}CI', ci(x['ci95'], 1, 2))
        M(f'cross{nm}Viable', cr['grippers'][g]['viable_parts'])
    M('devPoneRatio', f"{pw['N_F']['P1: Joint N_F < M0 (one-sided Wilcoxon, Holm step 0.025/3)']['development_ratio']:.2f}")
    M('powerPtwo', pw['non_inferiority']['Joint non-inferior to M0, robustness (v3), margin 5 pp']['power']['one-sided 0.025/3 (Holm, family of 3)']['200'])
